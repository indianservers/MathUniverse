import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';

const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
await page.goto('http://127.0.0.1:5173/workspace/data/cas', { waitUntil: 'networkidle' });
await page.getByTestId('workspace-cas-studio').waitFor();
const composer = page.locator('.cas-composer textarea');
await page.locator('.cas-composer select').selectOption('factor');
await composer.fill('x^2-17*x+16');
await page.locator('.cas-composer button.primary').click();
await page.waitForFunction(() => document.querySelectorAll('.cas-object-row').length === 5);
const beforeReload = await page.locator('.cas-object-row').count();
await page.reload({ waitUntil: 'networkidle' });
await page.getByTestId('workspace-cas-studio').waitFor({ timeout: 30_000 });
const afterReload = await page.locator('.cas-object-row').count();
const restored = await page.getByText('x^2-17*x+16', { exact: true }).count();
await fs.writeFile('test-evidence/phase-3/cas/persistence-results.json', JSON.stringify({ beforeReload, afterReload, restored }, null, 2));
await page.screenshot({ path: 'test-evidence/phase-3/cas/CAS-069-reloaded-session.png', fullPage: true });
await browser.close();
