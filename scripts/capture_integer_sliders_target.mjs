import { chromium } from "playwright";
import { copyFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const out = path.join(root, "test-evidence", "lesson-ui-upgrade");
const reference = "D:\\Math App Screenshots for UI Update\\Updated UI\\0022-interactive-foundational-advanced-algebra-and-dynamic-variables-integer-sliders-redesigned.png";
const url = process.env.LESSON_URL ?? "http://localhost:2245/lessons/core-workspaces/22-integer-sliders";
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1217, height: 1292 } });
const consoleMessages = [];
page.on("console", (message) => { if (["error", "warning"].includes(message.type())) consoleMessages.push(`${message.type()}: ${message.text()}`); });
await page.goto(url, { waitUntil: "domcontentloaded", timeout: 180000 });
const node = page.getByTestId("algebra-mockup-0022");
await node.waitFor({ timeout: 180000 });
const state = () => node.evaluate((element) => Object.fromEntries(["data-x", "data-y", "data-view", "data-actions"].map((name) => [name.replace("data-", ""), element.getAttribute(name)])));
const checks = { initial: await state() };
await page.getByLabel("Integer slider x drag control").evaluate((input) => { input.value = "1.6"; input.dispatchEvent(new Event("input", { bubbles: true })); input.dispatchEvent(new Event("change", { bubbles: true })); });
checks.fractionalSnap = await state();
await page.locator(".integer-range button").filter({ hasText: "-2" }).click();
checks.tick = await state();
await page.getByRole("button", { name: /Next x = -1/ }).click();
checks.next = await state();
await page.getByRole("button", { name: /Previous x = -2/ }).click();
checks.previous = await state();
await page.getByRole("button", { name: /Know more/ }).click();
checks.view = await state();
await page.evaluate(() => window.scrollTo(0, 0));
const metrics = await page.evaluate(() => {
  const region = (selector) => { const rect = document.querySelector(selector)?.getBoundingClientRect(); return rect ? { top: rect.top, bottom: rect.bottom, height: rect.height, left: rect.left, right: rect.right, width: rect.width } : null; };
  return { viewport: { width: innerWidth, height: innerHeight }, document: { width: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight }, horizontalOverflow: document.documentElement.scrollWidth > innerWidth, surface: region(".integer-slider-page"), regions: { header: region(".integer-header"), tabs: region(".integer-tabs"), main: region(".integer-main"), lab: region(".integer-lab"), side: region(".integer-side > section"), calculation: region(".integer-calculation"), lower: region(".integer-lower"), neighbors: region(".integer-neighbors"), footer: region(".integer-footer") } };
});
await page.reload({ waitUntil: "domcontentloaded" });
await page.getByTestId("algebra-mockup-0022").waitFor();
checks.reset = await state();
const passed = checks.initial.x === "3" && checks.initial.y === "9" && checks.fractionalSnap.x === "2" && checks.fractionalSnap.y === "7" && checks.tick.x === "-2" && checks.tick.y === "-1" && checks.next.x === "-1" && checks.next.y === "1" && checks.previous.x === "-2" && checks.view.view === "4" && checks.reset.x === "3" && checks.reset.y === "9" && !metrics.horizontalOverflow && consoleMessages.length === 0;
await page.screenshot({ path: path.join(out, "0022-desktop.png") });
await copyFile(reference, path.join(out, "0022-reference.png"));
const report = { mockup: "0022", lessonId: 22, route: "/lessons/core-workspaces/22-integer-sliders", objectModel: "discrete-integer-snap-iteration-table-staircase-plot-linked-affine-calculation-model", checks, metrics, consoleMessages, passed };
await writeFile(path.join(out, "0022-dedicated-target-validation.json"), `${JSON.stringify(report, null, 2)}\n`);
console.log(JSON.stringify(report, null, 2));
await browser.close();
process.exit(passed ? 0 : 1);
