import fs from 'node:fs';import path from 'node:path';import postcss from 'postcss';
const groups=new Map();const walk=dir=>fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(dir,e.name)):e.name.endsWith('.css')?[path.join(dir,e.name)]:[]);
const hexColors=v=>[...v.matchAll(/#([a-f0-9]{6}|[a-f0-9]{3})\b/gi)].map(m=>{let h=m[1];if(h.length===3)h=[...h].map(c=>c+c).join('');return [0,2,4].map(i=>parseInt(h.slice(i,i+2),16)/255);});
const hexes=v=>[...hexColors(v),...[...v.matchAll(/rgba?\(([^)]+)\)/gi)].flatMap(m=>{const nums=m[1].match(/[\d.]+/g)?.map(Number)??[];if(nums.length<3||(nums.length>3&&nums[3]<.6))return [];return [nums.slice(0,3).map(n=>n/(m[1].includes('%')?100:255))];})];
const lum=rgb=>rgb.reduce((s,c,i)=>s+c*[.2126,.7152,.0722][i],0);
for(const file of walk('src')){
 if(file.includes('styles')||file.includes('mobile')||file.includes('native'))continue;
 const root=postcss.parse(fs.readFileSync(file,'utf8'));
 root.walkRules(rule=>{
  if(!rule.selector||rule.selector.includes('.dark')||rule.selector.includes('data-chrome-theme')||rule.selector.includes('data-geometry-theme'))return;
  const selectors=postcss.list.comma(rule.selector).filter(s=>s.startsWith('.')&&!/svg|canvas|::|:before|:after|:root|scene|board-svg|color-blind|high-contrast/.test(s));
  if(!selectors.length)return;
  for(const apply of rule.nodes.filter(n=>n.type==='atrule'&&n.name==='apply')){
   const tokens=apply.params.split(/\s+/),values=[];
   if(tokens.some(t=>/^(bg-white(?:\/\d+)?|bg-(slate|gray|zinc|neutral|cyan|blue|violet|emerald|amber)-(50|100))$/.test(t)))values.push('background:var(--app-surface)!important');
   if(tokens.some(t=>/^text-(slate|gray|zinc|neutral)-(600|700|800|900|950)$/.test(t)))values.push('color:var(--app-text)!important');
   else if(tokens.some(t=>/^text-(slate|gray|zinc|neutral)-(400|500)$/.test(t)))values.push('color:var(--app-muted)!important');
   if(tokens.some(t=>/^border-(slate|gray|zinc|neutral)-(100|200|300)$/.test(t)))values.push('border-color:var(--app-border)!important');
   for(const value of values){const set=groups.get(value)??new Set();selectors.forEach(s=>set.add(s));groups.set(value,set);}
  }
  for(const decl of rule.nodes.filter(n=>n.type==='decl')){
   const colors=hexes(decl.value);if(!colors.length||decl.value.includes('var('))continue;
   let value;
   if(decl.prop.startsWith('--')&&colors.length===1){
    const name=decl.prop.toLowerCase(),rgb=colors[0];
    let token;
    if(/(?:ink|text|foreground|label|fg)$/.test(name)&&lum(rgb)<.6)token='text';
    else if(/(?:muted|secondary-text|subtext)$/.test(name))token='muted';
    else if(/(?:paper|surface|panel|card|background|bg)$/.test(name)&&lum(rgb)>.7)token='surface';
    else if(/(?:border|line)$/.test(name)&&lum(rgb)>.5)token='border';
    else if(/(?:violet|purple)$/.test(name))token='violet';
    else if(/(?:blue)$/.test(name))token='blue';
    else if(/(?:cyan|teal)$/.test(name))token='cyan';
    if(token)value=`${decl.prop}:var(--app-${token})!important`;
   }

   if(['background','background-color'].includes(decl.prop)&&colors.every(c=>lum(c)>.8))value='background:var(--app-surface)!important';
   if(decl.prop==='color'&&colors.length===1&&lum(colors[0])<.45){
    const [r,g,b]=colors[0],s=Math.max(r,g,b)-Math.min(r,g,b);
    const token=s<.22?'text':b>r&&b>g?(r>g*1.2?'violet':'blue'):g>r*1.2?'cyan':r>g*1.4?'rose':r>.4&&g>.25&&b<.2?'amber':'text';
    value=`color:var(--app-${token})!important`;
   }
   if(decl.prop==='border-color'&&colors.every(c=>lum(c)>.6))value='border-color:var(--app-border)!important';
   if(value){const set=groups.get(value)??new Set();selectors.forEach(s=>set.add(s));groups.set(value,set);}
  }
 });
}
const guard=':not([data-chrome-theme="light"]):not([data-geometry-theme="light"]):not([data-chrome-theme="light"] *):not([data-geometry-theme="light"] *)';
fs.writeFileSync('src/styles/legacyDarkTheme.generated.css','/* Generated by scripts/build-app-dark-theme.mjs. Scoped to dark mode; independent light workspace themes retain their own colors. */\n'+[...groups].flatMap(([value,selectors])=>{const list=[...selectors];return Array.from({length:Math.ceil(list.length/128)},(_,i)=>`${list.slice(i*128,(i+1)*128).map(selector=>`html.dark #root ${selector}:where(${guard})`).join(',')} {${value}}`);}).join('\n')+'\n');
console.log('Dark theme rules for '+[...groups.values()].reduce((n,s)=>n+s.size,0)+' legacy selectors');
