import { chromium } from "playwright";
import { copyFile, writeFile } from "node:fs/promises";
import path from "node:path";

/* global document, innerWidth, innerHeight */
const root = process.cwd();
const out = path.join(root, "test-evidence", "lesson-ui-upgrade");
const reference = "D:\\Math App Screenshots for UI Update\\Updated UI\\0186-interactive-intermediate-advanced-functions-function-concept-redesigned.png";
const url = process.env.LESSON_URL ?? "http://127.0.0.1:2254/lessons/graphs-and-functions/129-function-concept";
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 925, height: 1701 } });
const page = await context.newPage();
const consoleMessages = [];
page.on("console", (message) => { if (["error", "warning"].includes(message.type())) consoleMessages.push(`${message.type()}: ${message.text()}`); });
await page.goto(url, { waitUntil: "domcontentloaded", timeout: 180000 });
const node = page.getByTestId("graph-mockup-0186");
await node.waitFor({ timeout: 600000 });
const names = ["a", "b", "samples", "outputs", "practice", "actions"];
const state = () => node.evaluate((element, attributes) => Object.fromEntries(attributes.map((name) => [name, element.getAttribute(`data-${name}`)])), names);
const checks = { initial: await state() };
const dragFraction = async (locator, startFraction, deltaFraction) => {
  const box = await locator.boundingBox();
  if (!box) throw new Error("Drag target has no box");
  const x = box.x + box.width * startFraction;
  const y = box.y + box.height / 2;
  await page.mouse.move(x, y);
  await page.mouse.down();
  await page.mouse.move(x + box.width * deltaFraction, y, { steps: 9 });
  await page.mouse.up();
};
await dragFraction(node.getByRole("slider", { name: "Function rate a" }), .625, .075);
checks.rate = await state();
await dragFraction(node.getByRole("slider", { name: "Function start value b" }), .6, -.2);
checks.start = await state();
const firstPoint = node.getByRole("slider", { name: "Drag function input 1" });
const graphBox = await node.locator(".fun129-graph").boundingBox();
const pointBox = await firstPoint.boundingBox();
if (!graphBox || !pointBox) throw new Error("Graph drag geometry unavailable");
await page.mouse.move(pointBox.x + pointBox.width / 2, pointBox.y + pointBox.height / 2);
await page.mouse.down();
await page.mouse.move(pointBox.x + pointBox.width / 2 - graphBox.width * (39 / 540), pointBox.y + pointBox.height / 2, { steps: 8 });
await page.mouse.up();
checks.pointDrag = await state();
const secondPoint = node.getByRole("slider", { name: "Drag function input 2" });
await secondPoint.focus();
await secondPoint.press("ArrowRight");
checks.pointKeyboard = await state();
const practice = node.getByRole("spinbutton", { name: "Practice function input" });
await practice.fill("5");
await node.getByRole("button", { name: /g\(5\) = 7/ }).click();
checks.practice = await state();
await node.getByRole("button", { name: "Examples", exact: true }).click();
checks.example = await state();
await node.getByRole("button", { name: "Reset", exact: true }).click();
checks.reset = await state();
const metrics = await page.evaluate(() => {
  const region = (selector) => { const rect = document.querySelector(selector)?.getBoundingClientRect(); return rect ? { top: rect.top, bottom: rect.bottom, height: rect.height, left: rect.left, right: rect.right, width: rect.width } : null; };
  return { viewport: { width: innerWidth, height: innerHeight }, document: { width: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight }, horizontalOverflow: document.documentElement.scrollWidth > innerWidth, verticalOverflow: document.documentElement.scrollHeight > innerHeight, regions: { surface: region(".fun129-page"), intro: region(".fun129-intro"), tabs: region(".fun129-tabs"), lab: region(".fun129-lab"), layout: region(".fun129-layout"), machine: region(".fun129-machine"), graph: region(".fun129-plot"), rail: region(".fun129-rail"), tags: region(".fun129-tags"), navigation: region(".fun129-adjacent"), footer: region(".fun129-footer") } };
});
const consistent = (snapshot) => snapshot.samples.split(",").map(Number).every((x, index) => Math.abs((Number(snapshot.a) * x + Number(snapshot.b)) - Number(snapshot.outputs.split(",")[index])) < .001);
const passed = checks.initial.a === "1.25" && checks.initial.b === "1" && checks.initial.samples === "-2,0,2" && checks.initial.outputs === "-1.5,1,3.5" && checks.rate.a !== checks.initial.a && consistent(checks.rate) && checks.start.b !== checks.rate.b && consistent(checks.start) && checks.pointDrag.samples === "-3,0,2" && consistent(checks.pointDrag) && checks.pointKeyboard.samples === "-3,1,2" && consistent(checks.pointKeyboard) && checks.practice.practice === "5,7,true" && checks.example.a === "2" && checks.example.b === "-3" && checks.example.samples === "-1,1,3" && checks.example.outputs === "-5,-1,3" && checks.reset.a === "1.25" && checks.reset.b === "1" && checks.reset.samples === "-2,0,2" && !metrics.horizontalOverflow && !metrics.verticalOverflow && consoleMessages.length === 0;
await page.screenshot({ path: path.join(out, "0186-desktop.png") });
await copyFile(reference, path.join(out, "0186-reference.png"));
const report = { mockup: "0186", lessonId: 129, route: "/lessons/graphs-and-functions/129-function-concept", checks, metrics, consoleMessages, passed };
await writeFile(path.join(out, "0186-dedicated-target-validation.json"), `${JSON.stringify(report, null, 2)}\n`);
console.log(JSON.stringify(report, null, 2));
