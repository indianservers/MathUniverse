def ts_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def live_ts(expr: str) -> str:
    return expr


def write_files(all_seeds):
    overlay_parts = []
    spec_parts = []
    example_parts = []
    ids = []
    for seed in all_seeds:
        i, title, chart, ctitle, x, y, series, live, bars, points, definition, intro, how, why = seed
        ids.append(i)
        if len(definition) < 120:
            definition = definition + f" In {title}, that statement is the exact rule used by the labelled chart and the three numerical examples."
        if len(intro) < 220:
            intro = (
                intro
                + f" {title} keeps one numerical story on the labelled chart, the interactive probe, and the three worked calculations so the original interaction canvas does not have to change."
            )
        examples = EXAMPLES.get(i) or number_examples(i, title)
        worked = ",\n      ".join(
            '{ prompt: "%s", steps: [%s], answer: "%s" }'
            % (ts_escape(p), ", ".join(f'"{ts_escape(s)}"' for s in steps), ts_escape(a))
            for p, steps, a in examples
        )
        overlay_parts.append(
            f'''  {i}: {{
    introduction: "{ts_escape(intro)}",
    definition: "{ts_escape(definition)}",
    basicIdea: "{ts_escape(intro.split(".")[0])}.",
    howItWorks: "{ts_escape(how)}",
    whyItWorks: "{ts_escape(why)}",
    worked: [
      {worked},
    ],
  }}'''
        )
        bar_ts = ", ".join(f'["{lab}", {val}, "{col}"]' for lab, val, col in bars)
        pt_ts = ", ".join(f"[{a}, {b}]" for a, b in points)
        spec_parts.append(
            f'  {i}: spec("{chart}", "{ts_escape(ctitle)}", "{ts_escape(x)}", "{ts_escape(y)}", "{ts_escape(series)}", {live}, [\n    {bar_ts}\n  ], [{pt_ts}]),'
        )
        ex_ts = []
        for p, steps, a in examples:
            working = ts_escape(steps[0])
            result = ts_escape(steps[-1] if len(steps) > 1 else a)
            ex_ts.append(f'    calculation("{ts_escape(p)}", "{working}", "{result}", "{ts_escape(a)}"),')
        example_parts.append(f"  {i}: [\n" + "\n".join(ex_ts) + "\n  ]")

    overlay = '''import type { StrengthenedLesson, WorkedExample } from "./strengthenedLessonSchema";

type HandOverlay = {
  introduction: string;
  definition: string;
  basicIdea: string;
  howItWorks: string;
  whyItWorks: string;
  worked: Array<Pick<WorkedExample, "prompt" | "steps" | "answer">>;
};

const overlays: Record<number, HandOverlay> = {
%s
};

export function applyBatch2HandOverlay(lesson: StrengthenedLesson): StrengthenedLesson {
  const overlay = overlays[Number(lesson.id)];
  if (!overlay) return lesson;
  const workedExamples: WorkedExample[] = [
    ...overlay.worked.map((example, index) => ({
      id: `${lesson.id}-batch2-worked-${index + 1}`,
      prompt: example.prompt,
      steps: example.steps,
      answer: example.answer,
    })),
    ...lesson.workedExamples.filter(
      (example) =>
        !overlay.worked.some(
          (item) => item.prompt.trim().toLowerCase() === example.prompt.trim().toLowerCase(),
        ),
    ),
  ];
  return {
    ...lesson,
    introduction: overlay.introduction,
    basicIdea: overlay.basicIdea,
    howItWorks: overlay.howItWorks,
    whyItWorks: overlay.whyItWorks,
    definitions: [
      { id: `${lesson.id}-batch2-definition`, statement: overlay.definition },
      ...lesson.definitions,
    ],
    workedExamples,
  };
}

export const batch2HandAuthoredLessonIds = Object.keys(overlays).map(Number);
''' % (",\n".join(overlay_parts))

