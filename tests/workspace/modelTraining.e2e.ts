import { test, expect } from '@playwright/test';

test('bulk training exports real weights, tests predictions, and restores from IndexedDB', async ({ page }) => {
  test.setTimeout(120000);
  await page.goto('/model-training');
  await page.getByText('Legacy intent classifier · existing Training Lab',{exact:true}).click();
  await expect(page.getByRole('heading', { name: 'Teach language for your math workspace.' })).toBeVisible();
  const sampleDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download 15 sample rows' }).click();
  expect((await sampleDownload).suggestedFilename()).toBe('math-robo-15-samples.jsonl');
  await page.getByText('View all 15 sample rows', { exact: true }).click();
  await expect(page.locator('#dataset tbody tr')).toHaveCount(15);
  const words = ['please','kindly','now','quickly','carefully','hello','today','here','again','first','next','then','also','finally','simply','slowly','accurately','clearly','neatly','immediately'];
  const rows = words.flatMap(word => ['circle','square'].map(label => ({ phrase: `${word} draw ${label}`, canonical: `Create ${label}`, label, mode: 'geometry2d' })));
  await expect(page.getByLabel('Upload training dataset')).toBeEnabled();
  await page.getByLabel('Upload training dataset').setInputFiles({ name: 'reviewed.jsonl', mimeType: 'application/x-ndjson', buffer: Buffer.from(rows.map(row => JSON.stringify(row)).join('\n')) });
  await expect(page.locator('#train [role="status"]')).toContainText('40 valid rows');
  await page.getByLabel('Epochs', { exact: true }).fill('2');
  await page.getByRole('button', { name: 'Start training', exact: true }).click();
  await expect(page.locator('#train [role="status"]')).toContainText('Training complete', { timeout: 60000 });
  await expect(page.getByText('Trained model available', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Predict operation', exact: true }).click();
  await expect(page.locator('.mt-predictions li')).toHaveCount(3);
  const files: string[] = [];
  page.on('download', download => files.push(download.suggestedFilename()));
  await page.getByRole('button', { name: 'Download model.json + weights.bin', exact: true }).click();
  await expect.poll(() => files).toContain('math-robo-trained.json');
  await expect.poll(() => files).toContain('math-robo-trained.weights.bin');
  await page.reload();
  await page.getByText('Legacy intent classifier · existing Training Lab',{exact:true}).click();
  await expect(page.locator('#train [role="status"]')).toContainText('Saved model restored', { timeout: 30000 });
  await page.getByRole('button', { name: 'Predict operation', exact: true }).click();
  await expect(page.locator('.mt-predictions li')).toHaveCount(3);
  await page.getByRole('heading', { name: 'Teach language for your math workspace.' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/model-training/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('heading', { name: 'Teach language for your math workspace.' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/model-training/mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
