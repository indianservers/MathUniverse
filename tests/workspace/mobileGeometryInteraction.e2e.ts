import { expect, test } from "@playwright/test";

test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });

test("2D geometry creates, moves, and restores points with mobile tools", async ({ page }) => {
  test.setTimeout(120_000);
  await page.goto("/workspace/geometry");
  const root = page.locator(".geometry-studio-shell");
  await expect(root).toBeVisible({ timeout: 30_000 });
  const board = page.getByTestId("workspace-geometry-board");
  await expect(board).toBeVisible();
  const rect = await board.boundingBox();
  expect(rect!.width).toBeGreaterThan(300);
  expect(rect!.height).toBeGreaterThan(400);
  const tools = page.getByRole("navigation", { name: "Essential geometry tools" });
  await tools.getByRole("button", { name: "Point" }).click();
  await board.click({ position: { x: rect!.width * 0.35, y: rect!.height * 0.4 } });
  await board.click({ position: { x: rect!.width * 0.65, y: rect!.height * 0.6 } });
  await expect(board.locator("[data-point-id]")).toHaveCount(2);
  const first = board.locator("[data-point-id]").first();
  const firstHitBox = await first.boundingBox();
  expect(firstHitBox!.width).toBeGreaterThanOrEqual(42);
  expect(firstHitBox!.height).toBeGreaterThanOrEqual(42);
  const xBefore = Number(await first.getAttribute("cx"));
  await tools.getByRole("button", { name: "Select" }).click();
  const pointBox = await first.boundingBox();
  await page.mouse.move(pointBox!.x + pointBox!.width / 2, pointBox!.y + pointBox!.height / 2);
  await page.mouse.down();
  await page.mouse.move(pointBox!.x + pointBox!.width / 2 + 35, pointBox!.y + pointBox!.height / 2 + 10, { steps: 6 });
  await page.mouse.up();
  await expect.poll(async () => Number(await first.getAttribute("cx"))).not.toBe(xBefore);
  await tools.getByRole("button", { name: "Undo geometry change" }).click();
  await expect(board.locator("[data-point-id]")).toHaveCount(2);
  await expect.poll(async () => Number(await first.getAttribute("cx"))).toBeCloseTo(xBefore, 0);
  await page.getByRole("button", { name: "Open workspace panels" }).click();
  await expect(page.getByRole("dialog", { name: "tools panel" })).toBeVisible();
  await page.getByRole("button", { name: "Close panel" }).click();
  await expect(root).toHaveAttribute("data-mws-overlay", "");
  await page.setViewportSize({ width: 844, height: 390 });
  await expect(board).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(board.locator("[data-point-id]")).toHaveCount(2);
});

test("2D geometry line tools keep dependent geometry attached to touch sized points", async ({ page }) => {
  test.setTimeout(120_000);
  await page.goto("/workspace/geometry");
  const board = page.getByTestId("workspace-geometry-board");
  const tools = page.getByRole("navigation", { name: "Essential geometry tools" });
  await expect(board).toBeVisible({ timeout: 30_000 });
  const rect = (await board.boundingBox())!;
  await tools.getByRole("button", { name: "Point" }).click();
  await board.click({ position: { x: rect.width * 0.3, y: rect.height * 0.35 } });
  await board.click({ position: { x: rect.width * 0.7, y: rect.height * 0.6 } });
  await expect(board.locator("[data-point-id]")).toHaveCount(2);
  const points = board.locator("[data-point-id]");
  await tools.getByRole("button", { name: "Line" }).click();
  await points.first().tap();
  await points.nth(1).tap();
  const line = board.locator('[data-object-type="line"]').first();
  await expect(line).toBeVisible();
  await tools.getByRole("button", { name: "Select" }).click();
  await line.tap();
  await expect(board.locator(".geometry-selected-glow").first()).toBeVisible();
  const xBefore = Number(await line.getAttribute("x1"));
  const pointBox = (await points.first().boundingBox())!;
  await page.mouse.move(pointBox.x + pointBox.width / 2, pointBox.y + pointBox.height / 2);
  await page.mouse.down();
  await page.mouse.move(pointBox.x + pointBox.width / 2 + 40, pointBox.y + pointBox.height / 2 + 20, { steps: 5 });
  await page.mouse.up();
  await expect.poll(async () => Number(await line.getAttribute("x1"))).not.toBe(xBefore);
  await page.getByRole("button", { name: "Open workspace panels" }).click();
  await page.getByRole("button", { name: "Reset", exact: true }).click();
  await expect(board.locator("[data-point-id]")).toHaveCount(0);
  await expect(board.locator('[data-object-type="line"]')).toHaveCount(0);
  await page.getByRole("button", { name: "Close panel" }).click();
  await tools.getByRole("button", { name: "Point" }).click();
  await board.click({ position: { x: rect.width * 0.4, y: rect.height * 0.45 } });
  await expect(board.locator("[data-point-id]")).toHaveCount(1);
});
