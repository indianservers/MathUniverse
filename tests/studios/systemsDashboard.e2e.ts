import {test,expect} from '@playwright/test';
const modes=['Graphing','Substitution','Elimination','Matrices','Inequalities'];
test('all five reference dashboards render linked solutions on desktop and mobile',async({page})=>{
 test.setTimeout(120_000);
 await page.setViewportSize({width:1440,height:1000});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 for(const mode of modes){
  await page.goto(`/algebra/systems?mode=${mode}`);
  const dashboard=page.locator('.systems-dashboard');await expect(dashboard).toHaveAttribute('data-system-mode',mode);
  await expect(dashboard.locator('.sys-columns>.sys-panel')).toHaveCount(3);
  if(mode!=='Inequalities')await expect(dashboard.locator('.sys-solution-badge')).toContainText('(1, 3)');
  expect(await dashboard.evaluate(el=>el.scrollWidth<=el.clientWidth+1),mode).toBe(true);
  await page.evaluate(()=>document.documentElement.classList.remove('dark'));
  await dashboard.screenshot({animations:'disabled',path:`artifacts/systems-dashboard-${mode.toLowerCase()}.png`});
  await page.setViewportSize({width:390,height:844});
  expect(await dashboard.evaluate(el=>el.scrollWidth<=el.clientWidth+1),`${mode} mobile`).toBe(true);
  await page.setViewportSize({width:1440,height:1000});
 }
 expect(errors).toEqual([]);
});
