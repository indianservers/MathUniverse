export function enhancementsFor(page: CalculusStudioPage): StudioEnhancement[] {
  if (page === "home") return calculusStudioEnhancements;
  return calculusStudioEnhancements.filter((item) => item.page === page);
}

export function enhancementCounts(page: CalculusStudioPage = "home") {
  const items = enhancementsFor(page);
  return {
    total: items.length,
    ui: items.filter((item) => item.kind === "ui").length,
    ux: items.filter((item) => item.kind === "ux").length,
    content: items.filter((item) => item.kind === "content").length,
  };
}
