import type { CalculusStudioPage } from "./calculusStudioSession";

export type EnhancementKind = "ui" | "ux" | "content";

export type StudioEnhancement = {
  id: string;
  page: Exclude<CalculusStudioPage, "home">;
  kind: EnhancementKind;
  title: string;
  detail: string;
};

function pack(
  page: Exclude<CalculusStudioPage, "home">,
  prefix: string,
  rows: Array<[EnhancementKind, string, string]>,
): StudioEnhancement[] {
  return rows.map(([kind, title, detail], index) => ({
    id: `${prefix}-${String(index + 1).padStart(2, "0")}`,
    page,
    kind,
    title,
    detail,
  }));
}

