export type GatewayExamItem = {
  prompt: string;
  answer: string;
  acceptable?: readonly string[];
};

export type GatewayEnhancement = {
  id: number;
  title: string;
  liveLabel: string;
  liveValue: (t: number) => string;
  misconception: { wrong: string; correction: string };
  unlocks: { ids: readonly number[]; sentence: string; nextHref: string; nextLabel: string };
  exams: readonly [GatewayExamItem, GatewayExamItem, GatewayExamItem];
};

function g(
  id: number,
  title: string,
  liveLabel: string,
  liveValue: (t: number) => string,
  wrong: string,
  correction: string,
  unlockIds: readonly number[],
  sentence: string,
  nextHref: string,
  nextLabel: string,
  exams: readonly [GatewayExamItem, GatewayExamItem, GatewayExamItem],
): GatewayEnhancement {
  return {
    id,
    title,
    liveLabel,
    liveValue,
    misconception: { wrong, correction },
    unlocks: { ids: unlockIds, sentence, nextHref, nextLabel },
    exams,
  };
}

const exam = (prompt: string, answer: string, ...acceptable: string[]): GatewayExamItem => ({
  prompt,
  answer,
  acceptable,
});

