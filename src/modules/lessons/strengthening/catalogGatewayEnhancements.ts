export function normalizeGatewayAnswer(value: string) {
  return value.trim().toLowerCase().replace(/\s+/g, "").replace(/−/g, "-");
}

export function gatewayAnswerMatches(item: GatewayExamItem, value: string) {
  const actual = normalizeGatewayAnswer(value);
  const allowed = [item.answer, ...(item.acceptable ?? [])].map(normalizeGatewayAnswer);
  return allowed.includes(actual);
}
