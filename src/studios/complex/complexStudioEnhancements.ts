export function complexEnhancementsFor(page: ComplexStudioPageId): ComplexStudioEnhancement[] {
  if (page === "home") return complexStudioEnhancements;
  return complexStudioEnhancements.filter((item) => item.page === page);
}

export function complexEnhancementCounts(page: ComplexStudioPageId = "home") {
  const items = complexEnhancementsFor(page);
  return {
    total: items.length,
    ui: items.filter((item) => item.kind === "ui").length,
    ux: items.filter((item) => item.kind === "ux").length,
  };
}
